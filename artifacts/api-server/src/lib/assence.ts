interface PlanetPosition {
  sign: string;
  house: number;
  degree?: number | null;
  retrograde: boolean;
}

interface BirthChart {
  ascendant: string;
  midheaven: string;
  sun: PlanetPosition;
  moon: PlanetPosition;
  mercury: PlanetPosition;
  venus: PlanetPosition;
  mars: PlanetPosition;
  jupiter: PlanetPosition;
  saturn: PlanetPosition;
  uranus: PlanetPosition;
  neptune: PlanetPosition;
  pluto: PlanetPosition;
  chiron?: PlanetPosition;
  lilith?: PlanetPosition;
  northNode?: PlanetPosition;
  southNode?: PlanetPosition;
  aspects?: Array<{ planet1: string; planet2: string; type: string; orb?: number | null }>;
}

export function buildChartPrompt(data: {
  clientName: string;
  birthDate: string;
  birthTime?: string | null;
  birthPlace: string;
  clientAge?: number | null;
  autoCalculate?: boolean | null;
  birthChart?: unknown;
}): string {
  if (data.autoCalculate) {
    return `Por favor, realize a análise astrológica completa seguindo o método Assence para:

Nome: ${data.clientName}
Data de Nascimento: ${data.birthDate}
Hora de Nascimento: ${data.birthTime ?? "Não informada"}
Local de Nascimento: ${data.birthPlace}
${data.clientAge != null ? `Idade: ${data.clientAge} anos` : ""}

Com base nestes dados de nascimento, calcule as posições planetárias aproximadas (Sol, Lua, Mercúrio, Vênus, Marte, Júpiter, Saturno, Urano, Netuno, Plutão, Quíron, Nodo Norte/Sul, Lilith) para esta data, hora e local, identificando o Ascendente e Meio-do-Céu. Em seguida, realize a análise completa conforme as diretrizes do método Assence, seguindo a estrutura obrigatória com todos os combos de entrega para cada posição.`;
  }
  const chart = data.birthChart as BirthChart;

  const formatPlanet = (name: string, p: PlanetPosition) =>
    `${name}: ${p.sign}, Casa ${p.house}${p.degree != null ? `, ${p.degree}°` : ""}${p.retrograde ? " (Retrógrado)" : ""}`;

  const planetLines = [
    `Ascendente: ${chart.ascendant}`,
    `Meio do Céu (MC): ${chart.midheaven}`,
    formatPlanet("Sol", chart.sun),
    formatPlanet("Lua", chart.moon),
    formatPlanet("Mercúrio", chart.mercury),
    formatPlanet("Vênus", chart.venus),
    formatPlanet("Marte", chart.mars),
    formatPlanet("Júpiter", chart.jupiter),
    formatPlanet("Saturno", chart.saturn),
    formatPlanet("Urano", chart.uranus),
    formatPlanet("Netuno", chart.neptune),
    formatPlanet("Plutão", chart.pluto),
  ];

  if (chart.chiron) planetLines.push(formatPlanet("Quíron", chart.chiron));
  if (chart.lilith) planetLines.push(formatPlanet("Lilith", chart.lilith));
  if (chart.northNode) planetLines.push(formatPlanet("Nodo Norte", chart.northNode));
  if (chart.southNode) planetLines.push(formatPlanet("Nodo Sul", chart.southNode));

  const aspectLines =
    chart.aspects && chart.aspects.length > 0
      ? `\nASPECTOS:\n${chart.aspects.map((a) => `${a.planet1} ${a.type} ${a.planet2}${a.orb != null ? ` (orbe ${a.orb}°)` : ""}`).join("\n")}`
      : "";

  return `Por favor, realize a análise astrológica completa seguindo o método Assence para:

Nome: ${data.clientName}
Data de Nascimento: ${data.birthDate}
Hora de Nascimento: ${data.birthTime ?? "Não informada"}
Local de Nascimento: ${data.birthPlace}
${data.clientAge != null ? `Idade: ${data.clientAge} anos` : ""}

POSIÇÕES PLANETÁRIAS:
${planetLines.join("\n")}
${aspectLines}

Realize a análise completa conforme as diretrizes do método Assence, seguindo a estrutura obrigatória com todos os combos de entrega (análise da alma do planeta, Laboratório de Integração, Poder do Verbo, Reflexão e Conselho de Ouro) para cada posição.`;
}
